/** 한자 한 글자의 한글 음(音)을 읽어와요. */
export function getHanjaReading(char: string): string {
  try {
    return hanjaLib.translate(char, 'SUBSTITUTION') || char;
  } catch {
    return char;
  }
}

/** 한자 한 글자의 훈음(뜻+음) 풀이를 반환해요. 사전에 없으면 음만 반환해요. */
export function getHanjaGloss(char: string): string {
  const meaning = HANJA_MEANING[char];
  if (meaning) return meaning;
  const reading = getHanjaReading(char);
  return reading !== char ? `${reading} (자세한 뜻풀이는 준비 중)` : '뜻풀이 준비 중';
}
